<p><strong>Коротко:</strong> разработка мобильного приложения проходит семь этапов — аналитика и техническое задание, прототип, дизайн, разработка, тестирование, публикация и поддержка. Простое приложение или MVP проходит этот путь за 1–2 месяца, приложение средней сложности — за 3–4 месяца, сложный проект с интеграциями — за 5–6 месяцев.</p>

<h2>1. Аналитика и техническое задание</h2>
<p>Самый недооценённый этап. Мы разбираемся в бизнес-задаче, аудитории и конкурентах, описываем роли пользователей, сценарии и интеграции, а в итоге получаем техническое задание и смету.</p>
<p><strong>Что нужно от вас:</strong> описание идеи, примеры приложений, которые нравятся, понимание, кто будет пользоваться приложением. Если готового ТЗ нет — это нормально, мы составим его сами.</p>
<p><strong>Результат:</strong> ТЗ, список экранов, оценка сроков и стоимости, которые фиксируются в договоре.</p>

<h2>2. Прототип</h2>
<p>Схема всех экранов и переходов между ними без дизайна — серые блоки и кнопки. На прототипе дёшево менять логику: передвинуть кнопку в макете — минуты, переделать готовый экран в коде — дни.</p>
<p><strong>Что нужно от вас:</strong> пройти по прототипу как пользователь и сказать, всё ли логично.</p>

<h2>3. Дизайн</h2>
<p>Дизайнер отрисовывает экраны в фирменном стиле с учётом гайдлайнов Apple и Google: размеры кнопок, системные жесты, тёмная тема, разные размеры экранов. Отдельно готовятся иконка приложения и UI-кит для разработчиков.</p>
<p><strong>Результат:</strong> макеты всех экранов в Figma, которые вы утверждаете перед разработкой.</p>

