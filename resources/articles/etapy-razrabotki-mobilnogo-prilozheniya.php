    <li><strong>backend</strong> — сервер, база данных и API;</li>
    <li><strong>админ-панель</strong> — где вы управляете контентом, заказами и пользователями.</li>
</ul>
<p>Работаем короткими итерациями и показываем промежуточные сборки, чтобы вы видели прогресс, а не ждали результата несколько месяцев.</p>

<h2>5. Тестирование</h2>
<p>Проверяем функции, интерфейс и производительность на реальных устройствах разных размеров и версий системы, отдельно — оплату, push-уведомления, работу при плохом интернете. Перед публикацией вы получаете тестовую сборку и проверяете приложение сами.</p>

<h2>6. Публикация</h2>
<p>Готовим описание, скриншоты и иконку, заполняем анкеты о данных пользователей и отправляем приложение на модерацию Apple и Google. Приложение публикуется на аккаунты вашей компании. Подробно о требованиях и частых причинах отказа — в статье <a href="/articles/kak-opublikovat-prilozhenie-v-app-store-i-google-play">«Как опубликовать приложение в App Store и Google Play»</a>.</p>

<h2>7. Поддержка и развитие</h2>
<p>После запуска начинается работа с реальными пользователями: исправляем найденные ошибки, обновляем приложение под новые версии iOS и Android, смотрим аналитику и добавляем функции, которые действительно нужны.</p>

