<h2>Частые ошибки в ТЗ</h2>
<ul>
    <li><strong>«Как у Яндекс Еды, только дешевле».</strong> Крупные сервисы годами развивались командами в сотни человек. Опишите, что нужно именно вам на старте.</li>
    <li><strong>Забытая админ-панель.</strong> Приложение — только половина системы, вторая половина — панель, где сотрудники работают с заказами.</li>
    <li><strong>Всё сразу.</strong> Двадцать функций в первой версии — это долго и дорого. Лучше начать с <a href="/articles/chto-takoe-mvp-prilozheniya">MVP</a> и добавлять функции по отзывам пользователей.</li>
    <li><strong>Нет сценариев ошибок.</strong> Нет интернета, нет товара, отменили заказ — эти случаи тоже нужно описать.</li>
</ul>

